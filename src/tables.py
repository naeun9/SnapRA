def scenario_pair(situation_id: str):
    """Y-03 -> N-03, N-33 -> Y-33. 쌍이 없으면 None."""
    if not situation_id or len(situation_id) < 3:
        return None
    prefix, num = situation_id[0], situation_id[1:]
    if prefix == "Y":
        return "N" + num
    if prefix == "N":
        return "Y" + num
    return None


def is_normal(situation_id: str):
    """정상 True / 비정상 False / 판정 대상 아님 None."""
    if not situation_id:
        return None
    if situation_id.startswith("Y-"):
        return True
    if situation_id.startswith("N-"):
        return False
    return None


def describe(situation_id: str) -> str:
    """'추락 · 비계 공사 · 시스템 비계 작업발판 설치 불량' 형태로."""
    row = SCENARIOS.get(situation_id)
    if not row:
        return situation_id
    type_id, process_id, text = row
    return " · ".join(
        (ACCIDENT_TYPES.get(type_id, type_id), PROCESSES.get(process_id, process_id), text)
    )


